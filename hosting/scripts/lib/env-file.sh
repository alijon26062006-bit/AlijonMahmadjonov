# Определяет, какой .env принадлежит хостингу. Подключается через `source`.
#
# Раньше это был .env в корне репозитория — общий с Telegram-ботом учёта денег
# (bot/), который читает оттуда ту же переменную TELEGRAM_BOT_TOKEN. Из-за этого
# хостинг работал с токеном чужого бота, а два процесса опрашивали getUpdates
# одного бота и перехватывали сообщения друг у друга.

hosting_env_file() {
  local root="$1"
  if [[ -f "${root}/hosting/.env" ]]; then
    echo "${root}/hosting/.env"
  else
    echo "${root}/.env"   # запасной путь, пока install.sh не перенёс значения
  fi
}
