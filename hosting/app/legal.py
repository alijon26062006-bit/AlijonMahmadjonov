def _contacts(s: Settings) -> str:
    items = []
    if s.support_email:
        items.append(f"эл. почта {html.escape(s.support_email)}")
    if s.support_telegram:
        items.append(f"Telegram @{html.escape(s.support_telegram)}")
    if s.support_phone:
        items.append(f"телефон {html.escape(s.support_phone)}")
    return ", ".join(items) or "контакты, указанные на сайте"


