def render_legal(doc: str, s: Settings) -> str | None:
    if doc not in TITLES:
        return None
    title = TITLES[doc]
    brand = html.escape(s.brand_name)
    nav = " · ".join(f'<a href="/legal/{k}"{" aria-current=page" if k == doc else ""}>{v}</a>' for k, v in TITLES.items())
    return f"""<!doctype html>
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} — {brand}</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&display=swap">
<style>
:root {{ color-scheme: dark; }}
body {{ margin: 0; background: #080F24; color: #DCE3F8; font: 16px/1.65 Inter, system-ui, sans-serif; }}
main {{ max-width: 760px; margin: 0 auto; padding: 32px max(20px, env(safe-area-inset-left)) 64px; }}
a {{ color: #93B4FF; }}
h1 {{ font-size: 30px; line-height: 1.2; margin: 18px 0 8px; color: #fff; }}
h2 {{ font-size: 19px; margin: 30px 0 8px; color: #fff; }}
li {{ margin: 6px 0; }}
nav {{ font-size: 14px; color: #94A0C3; }}
nav a[aria-current] {{ color: #fff; font-weight: 600; text-decoration: none; }}
.back {{ display: inline-block; margin-bottom: 8px; text-decoration: none; font-weight: 600; }}
mark {{ background: #7C3AED33; color: #E9D5FF; padding: 0 4px; border-radius: 4px; }}
.updated {{ color: #94A0C3; font-size: 14px; }}
</style></head>
<body><main>
<a class="back" href="/">← {brand}</a>
<nav>{nav}</nav>
<h1>{title}</h1>
<p class="updated">Редакция действует с момента публикации на сайте.</p>
{_body(doc, s)}
</main></body></html>"""
