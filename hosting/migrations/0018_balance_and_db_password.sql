-- Баланс клиента в сомони. Хранится у пользователя, а история пополнений и
-- списаний — в payments: так баланс всегда можно пересчитать и сверить.
ALTER TABLE users
    ADD COLUMN balance_tjs DECIMAL(10,2) NOT NULL DEFAULT 0.00 AFTER plan_id;

-- Пароль пользователя базы, зашифрованный.
--
-- Клиент должен видеть свой пароль в панели (иначе после первого показа его
-- негде взять, а менять его — значит ломать все уже настроенные сайты).
-- Открытым текстом в базе панели такой пароль лежать не должен: дамп панельной
-- базы тогда сразу даёт доступ ко ВСЕМ базам всех клиентов. Поэтому здесь
-- шифротекст AES-256-GCM, ключ — в .env (APP_KEY), вне базы.
ALTER TABLE database_users
    ADD COLUMN password_enc TEXT NULL AFTER db_user;
