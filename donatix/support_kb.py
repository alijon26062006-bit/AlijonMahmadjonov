def kb_section(slug: str) -> dict[str, Any] | None:
    for s, ico, color, title, sub, items in KB:
        if s == slug:
            return {"slug": s, "icon": ico, "color": color, "title": title, "sub": sub, "faq": items}
    return None


def kb_index() -> list[dict[str, Any]]:
    """Для поиска на странице: каждый вопрос с разделом."""
    return [{"section": s, "title": title, "q": q, "a": a} for s, _, _, title, _, items in KB for q, a in items]
