--
-- Текст из настроек говорил «Я превращаю идеи…», хотя это описание
-- студии, а не личный блок основателя. По всему сайту голос теперь
-- один: студия — «мы», личный блок — «я».
--
-- Правим только нетронутое значение. Если владелец уже переписал
-- описание под себя, миграция его не тронет: сравнение идёт с точным
-- исходным текстом.
-- ============================================================

UPDATE site_settings
   SET value_ru = 'AVERIX — студия разработки цифровых продуктов. Мы превращаем идеи в работающие сайты, Telegram-ботов, сервисы и системы автоматизации.',
       updated_at = datetime('now')
 WHERE key = 'about_text'
   AND value_ru = 'AVERIX — студия разработки цифровых продуктов. Я превращаю идеи в работающие сайты, Telegram-боты, сервисы и системы автоматизации.';

