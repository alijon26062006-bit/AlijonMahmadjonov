"""Стиль каталога: один набор правил на все фотографии магазина.

Смысл файла в том, что художественных решений здесь ровно столько, сколько
записано, и модель не принимает их заново для каждого товара. Товар,
добавленный через год, попадёт в тот же формат, тот же масштаб и тот же
набор фонов, что и первый.

Меняете стиль — поднимаете STYLE_VERSION. Тогда видно, какие фотографии
обработаны по старым правилам, и их можно переделать из оригиналов.
"""
from dataclasses import dataclass

STYLE_VERSION = 1

# Формат карточки. 4:5 — вертикальный, одежда и обувь в нём смотрятся
# крупнее, чем в квадрате, а лента остаётся ровной.
CANVAS = (1200, 1500)

# Какую долю кадра занимает товар по большей стороне. 0.76 — это «крупно,
# но с воздухом»: мельче выглядит потерянным, крупнее упирается в края.
SUBJECT_RATIO = 0.76

# Товар стоит чуть выше центра: под ним остаётся место для тени, и кадр
# не кажется съехавшим вниз.
SUBJECT_SHIFT_Y = -0.02


@dataclass(frozen=True)
class Background:
    key: str
    title: str
    rgb: tuple[int, int, int]
    luma: float          # яркость фона, 0..255 — по ней считаем контраст


# Ограниченный набор. Ровно три нейтральных фона, никаких цветных: иначе
# каталог рассыпается на разные магазины.
BACKGROUNDS: dict[str, Background] = {
    "very_light": Background("very_light", "Очень светлый", (250, 250, 250), 250),
    "light": Background("light", "Светлый", (243, 243, 243), 243),
    "soft_gray": Background("soft_gray", "Светло-серый", (229, 229, 229), 229),
}
DEFAULT_BACKGROUND = "very_light"

# Границы яркости товара для выбора фона (0..255, по маске товара).
DARK_MAX = 90        # тёмный товар
LIGHT_MIN = 205      # очень светлый товар

# Минимальная разница яркости между краем товара и фоном. Если меньше —
# берём фон на ступень темнее, иначе белая коробка растворяется в белом.
MIN_EDGE_CONTRAST = 26

SHADOW = {
    "opacity": 0.16,     # еле заметная
    "blur": 26,          # мягкая, без резкой границы
    "squash": 0.13,      # высота тени от высоты товара
    "spread": 1.04,      # чуть шире самого товара
    "offset": 0.012,     # отступ от нижнего края товара, доля высоты кадра
}

JPEG_QUALITY = 88


def preset() -> dict:
    """Слепок стиля — уходит в запись фотографии, чтобы потом было видно,
    по каким правилам её обрабатывали."""
    return {
        "version": STYLE_VERSION,
        "canvas": list(CANVAS),
        "subject_ratio": SUBJECT_RATIO,
        "backgrounds": list(BACKGROUNDS),
        "shadow": SHADOW,
    }
