def _days_left(seconds: float) -> str:
    days = round(seconds / 86400)  # проверка раз в полчаса: 2,98 дня — это «3 дн.»
    if days >= 1:
        return f"{days} дн."
    return f"{max(1, int(seconds // 3600))} ч."


