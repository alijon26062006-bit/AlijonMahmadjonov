def program_overview(ready: int) -> str:
    lines = [f"🗺 <b>Программа курса: от 0 до 100%</b>\n",
             f"{len(MODULES)} модулей, {TOTAL_LESSONS} уроков. "
             f"Готово: {min(ready, TOTAL_LESSONS)}.\n"]
    for i, (title, goal, lessons) in enumerate(MODULES, 1):
        lines.append(f"<b>{i}. {title}</b> — {len(lessons)} ур.\n<i>{goal}</i>")
    lines.append("\nНажмите на модуль, чтобы увидеть все уроки 👇")
    return "\n".join(lines)


def module_text(index: int, ready: int) -> str:
    """index — номер модуля с нуля. Уроки нумеруются сквозь весь курс."""
    title, goal, lessons = MODULES[index]
    first = sum(len(m[2]) for m in MODULES[:index]) + 1
    lines = [f"<b>Модуль {index + 1}. {title}</b>", f"<i>{goal}</i>\n"]
    for n, lesson in enumerate(lessons, first):
        mark = "✅" if n <= ready else "⏳"
        lines.append(f"{mark} Урок {n}. {escape(lesson)}")
    lines.append("\n✅ — урок уже готов, ⏳ — выйдет по графику")
    return "\n".join(lines)


